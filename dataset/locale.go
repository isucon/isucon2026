var regionLanguages = map[string][]language{
	Asia:    {japanese, chinese, korean},
	Europe:  {english, french, german},
	America: {americanEnglish, spanish, portuguese},
}

// Use a separate stream so choosing a language never changes relationships,
// activity, image IDs, or the historical population. The user keeps one language.
func languageFor(region, userID string) language {
	languages := regionLanguages[region]
	return languages[newRand(0, "language-"+userID).IntN(len(languages))]
}

func localizeUser(seed uint64, index int, user *User) {
	l := languageFor(user.Region, user.ID)
	r := newRand(seed, "profile-text-"+user.ID)
	team := r.IntN(len(l.names))
	user.DisplayName = l.names[team]
	user.Username = fmt.Sprintf("%s_%d", l.handles[team], index)
	if user.Bio != "" {
		user.Bio = choose(r, l.bios)
	}
}
