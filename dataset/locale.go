var regionLanguages = map[string][]language{
	Asia:    {japanese, chinese, korean},
	Europe:  {english, french, german},
	America: {americanEnglish, spanish, portuguese},
}

// Use a separate stream so choosing a language never changes relationships,
// activity, image IDs, or the historical population. The user keeps one language.
func languageFor(region, userID string) language {
	languages := regionLanguages[region]
	return languages[newRand(0, "language-"+userID).IntN(len(languages))]
}

// Alternate ordinary names and invented nicknames within each region/language.
// Keep the first occurrence unchanged, adding the user index only on collision.
func localizeUsers(seed uint64, users []*User) {
	used := map[string]bool{}
	counts := map[string]int{}
	for index, user := range users {
		l := languageFor(user.Region, user.ID)
		r := newRand(seed, "profile-text-"+user.ID)
		key := user.Region + "/" + l.code
		names, handles := l.names, l.handles
		if counts[key]%2 == 0 {
			names, handles = l.personalNames, l.personalHandles
		}
		counts[key]++
		choice := r.IntN(len(names))
		user.DisplayName = names[choice]
		if used[user.DisplayName] {
			user.DisplayName = fmt.Sprintf("%s %d", user.DisplayName, index)
		}
		used[user.DisplayName] = true
		user.Username = fmt.Sprintf("%s_%d", handles[choice], index)
		if user.Bio != "" {
			user.Bio = choose(r, l.bios)
		}
	}
}
