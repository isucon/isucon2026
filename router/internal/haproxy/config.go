// Package haproxy renders the HAProxy configuration of the Router's HTTP data
// plane and sets the Portal's default country through the HAProxy runtime API.
package haproxy

import (
	"fmt"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"time"

	"github.com/isucon/isucon2026/router/internal/config"
	"github.com/isucon/isucon2026/router/internal/domain"
)

// Files written by Render into the HAProxy directory.
const (
	ConfigFile        = "haproxy.cfg"
	LuaFile           = "isureal.lua"
	DefaultCountryMap = "default-country.map"
)

// defaultCountryKey is the only key of the default country map.
const defaultCountryKey = "default"

// The delay action sleeps without blocking HAProxy's event loop.
const luaScript = `core.register_action("isureal_delay", { "http-req" }, function(_, ms)
  core.msleep(tonumber(ms))
end, 1)
`

// A Host that begins with a region's prefix goes to that region's server; any
// other Host, including an IP address, goes by the client's country.
var targets = []struct {
	name   string
	server domain.ServerID
	prefix string
}{
	{name: "app"},
	{name: string(domain.App1), server: domain.App1, prefix: "asia."},
	{name: string(domain.App2), server: domain.App2, prefix: "europe."},
	{name: string(domain.App3), server: domain.App3, prefix: "america."},
}

var regions = []domain.Region{domain.RegionAP, domain.RegionEU, domain.RegionUS}

var apps = []domain.ServerID{domain.App1, domain.App2, domain.App3}

// streamPath is the SSE endpoint. HAProxy sends the headers and the events of
// an unfinished response with MSG_MORE, which holds each of them for about
// 200 ms, so this path uses backends with "option http-no-delay". The option
// stays out of defaults because it costs CPU on large rate-limited responses.
const streamPath = "/api/notifications"

func streamBackend(server domain.ServerID) string { return string(server) + "_stream" }

// The benchmark marks its downloads of images and exports with this header.
// They go to isureal-digest (router/digest), which reads the app's response and
// answers with its digest, so that the Router forwards those bytes once instead
// of twice. Browsers never send the header.
const (
	benchmarkHeader = "x-benchmark-request-id"
	imagePathPrefix = "/api/images/"
	exportPath      = "/api/me/export"
)

func digestBackend(server domain.ServerID) string { return string(server) + "_digest" }

// route is one target and client region. Each country still gets its own
// bandwidth bucket, keyed by target and country.
type route struct {
	key    string
	server domain.ServerID
	class  domain.TrafficClass
}

func routes(profile domain.TrafficProfile) []route {
	result := make([]route, 0, len(targets)*len(regions))
	for _, target := range targets {
		for _, region := range regions {
			server := target.server
			if server == "" {
				server = domain.ServerForRegion(region)
			}
			result = append(result, route{
				key:    target.name + "/" + string(region),
				server: server,
				class:  profile.Class(region, domain.ServerRegion(server)),
			})
		}
	}
	return result
}

// Render returns the HAProxy files, keyed by file name. They depend only on
// the Router's static configuration. The default country map starts empty, so
// HAProxy answers 503 until the Controller applies the first Portal snapshot.
func Render(cfg config.Config) (map[string]string, error) {
	if err := cfg.Validate(); err != nil {
		return nil, err
	}
	all := routes(cfg.Traffic)
	delays := map[int64][]string{}
	bandwidths := map[uint64][]string{}
	for _, r := range all {
		if r.class.Delay > 0 {
			ms := int64((r.class.Delay + time.Millisecond - 1) / time.Millisecond)
			delays[ms] = append(delays[ms], r.key)
		}
		bandwidths[r.class.BandwidthBPS] = append(bandwidths[r.class.BandwidthBPS], r.key)
	}
	countries := map[domain.Region][]string{}
	for _, country := range domain.Countries() {
		region, _ := domain.CountryRegion(country)
		countries[region] = append(countries[region], country)
	}
	mapPath := filepath.Join(cfg.HAProxyDir, DefaultCountryMap)

	var b strings.Builder
	line := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }
	line("# Generated by isureal-router haproxy-config. Do not edit.")
	line("global")
	line("    maxconn 100000")
	line("    tune.bufsize 32768")
	line("    stats socket ipv4@%s level admin", cfg.HAProxyRuntimeAddress)
	if len(delays) > 0 {
		line("    lua-load %s", filepath.Join(cfg.HAProxyDir, LuaFile))
	}
	line("")
	// An upstream may stay silent for 60 seconds: twice the benchmark's 30 s
	// budget for /api/initialize (other requests get 15 s), which leaves room
	// for a slower benchmark. A refused connection fails at once instead of
	// retrying.
	line("defaults")
	line("    mode http")
	line("    maxconn 100000")
	line("    retries 0")
	line("    timeout connect 2s")
	line("    timeout http-request 30s")
	line("    timeout client 5m")
	line("    timeout http-keep-alive 1h")
	line("    timeout server 60s")
	line("")
	line("frontend edge")
	line("    bind %s", cfg.HTTPListenAddress)
	if cfg.HTTPSListenAddress != "" {
		line("    bind %s ssl crt %s", cfg.HTTPSListenAddress, cfg.TLSCertificate)
	}
	// Requests and responses each get the route's bandwidth; every target and
	// country pair has its own bucket in the bandwidth table.
	for _, bps := range slices.Sorted(maps.Keys(bandwidths)) {
		bytes := max(bps/8, 1)
		line("    filter bwlim-in up_%d limit %d key var(txn.route) table bandwidth", bps, bytes)
		line("    filter bwlim-out down_%d limit %d key var(txn.route) table bandwidth", bps, bytes)
	}
	line("    http-request set-var(txn.default_country) str(%s),map(%s)", defaultCountryKey, mapPath)
	line("    http-request return status 503 unless { var(txn.default_country) -m found }")
	line("    http-request set-var(txn.target) str(app)")
	for _, target := range targets {
		if target.prefix != "" {
			line("    http-request set-var(txn.target) str(%s) if { req.hdr(host) -i -m beg %s }", target.name, target.prefix)
		}
	}
	line("    http-request set-var(txn.country_headers) req.fhdr_cnt(x-country-code)")
	line("    http-request return status 400 if { var(txn.country_headers) -m int gt 1 }")
	line("    http-request set-var(txn.country) req.fhdr(x-country-code) if { var(txn.country_headers) -m int eq 1 }")
	line("    http-request set-var(txn.route) var(txn.target),concat(/,txn.country) if { var(txn.country_headers) -m int eq 1 }")
	line("    http-request set-var(txn.country) var(txn.default_country) if { var(txn.country_headers) -m int eq 0 }")
	line("    http-request set-var(txn.route) var(txn.target),concat(/default) if { var(txn.country_headers) -m int eq 0 }")
	line("    http-request set-header X-Country-Code %%[var(txn.country)] if { var(txn.country_headers) -m int eq 0 }")
	for _, region := range regions {
		line("    http-request set-var(txn.pair) var(txn.target),concat(/%s) if { var(txn.country) -m str %s }", region, strings.Join(countries[region], " "))
	}
	line("    http-request return status 400 unless { var(txn.pair) -m found }")
	for _, ms := range slices.Sorted(maps.Keys(delays)) {
		line("    http-request lua.isureal_delay %d if { var(txn.pair) -m str %s }", ms, strings.Join(delays[ms], " "))
	}
	for _, bps := range slices.Sorted(maps.Keys(bandwidths)) {
		keys := strings.Join(bandwidths[bps], " ")
		line("    http-request set-bandwidth-limit up_%d if { var(txn.pair) -m str %s }", bps, keys)
		line("    http-request set-bandwidth-limit down_%d if { var(txn.pair) -m str %s }", bps, keys)
	}
	line("    http-request set-header X-Client-IP %%[src] if { req.fhdr_cnt(x-client-ip) -m int eq 0 }")
	digest := cfg.DigestAddress != ""
	if digest {
		line("    acl bench_digest req.fhdr_cnt(%s) -m int gt 0", benchmarkHeader)
		line("    acl digest_path path_beg %s", imagePathPrefix)
		line("    acl digest_path path %s", exportPath)
	}
	for _, server := range apps {
		var keys []string
		for _, r := range all {
			if r.server == server {
				keys = append(keys, r.key)
			}
		}
		if digest {
			line("    use_backend %s if { method GET } bench_digest digest_path { var(txn.pair) -m str %s }", digestBackend(server), strings.Join(keys, " "))
		}
		line("    use_backend %s if { path %s } { var(txn.pair) -m str %s }", streamBackend(server), streamPath, strings.Join(keys, " "))
		line("    use_backend %s if { var(txn.pair) -m str %s }", server, strings.Join(keys, " "))
	}
	for _, server := range apps {
		upstream := fmt.Sprintf("%s:%d", cfg.Servers[server].ServerIP, cfg.UpstreamPort)
		line("")
		line("backend %s", server)
		line("    server %s %s", server, upstream)
		line("")
		line("backend %s", streamBackend(server))
		line("    option http-no-delay")
		line("    server %s %s", server, upstream)
		if !digest {
			continue
		}
		// isureal-digest gets the app's address and the route's bandwidth
		// limit, which it applies to the bodies HAProxy no longer forwards.
		// While it is down the app answers instead, without the benchmark's
		// header, and the benchmark compares the bytes.
		line("")
		line("backend %s", digestBackend(server))
		line("    acl digest_up srv_is_up(%s/digest)", digestBackend(server))
		line("    http-request del-header %s unless digest_up", benchmarkHeader)
		line("    http-request set-header X-Isureal-Upstream %s if digest_up", upstream)
		line("    http-request set-header X-Isureal-Route %%[var(txn.route)] if digest_up")
		limits := map[uint64][]string{}
		for _, r := range all {
			if r.server == server {
				limits[r.class.BandwidthBPS] = append(limits[r.class.BandwidthBPS], r.key)
			}
		}
		for _, bps := range slices.Sorted(maps.Keys(limits)) {
			line("    http-request set-header X-Isureal-Limit %d if digest_up { var(txn.pair) -m str %s }", max(bps/8, 1), strings.Join(limits[bps], " "))
		}
		line("    server digest %s check inter 1s fall 2 rise 2", cfg.DigestAddress)
		line("    server %s %s backup", server, upstream)
	}
	line("")
	line("backend bandwidth")
	line("    stick-table type string len 32 size 64 store bytes_in_rate(1s),bytes_out_rate(1s)")

	files := map[string]string{ConfigFile: b.String(), DefaultCountryMap: ""}
	if len(delays) > 0 {
		files[LuaFile] = luaScript
	}
	return files, nil
}

// Write replaces the files in dir.
func Write(dir string, files map[string]string) error {
	for name, content := range files {
		path := filepath.Join(dir, name)
		temporary := path + ".tmp"
		if err := os.WriteFile(temporary, []byte(content), 0o644); err != nil {
			return err
		}
		if err := os.Rename(temporary, path); err != nil {
			return err
		}
	}
	return nil
}
