package integration_test

import (
	"context"
	"fmt"
	"net/http"
	"testing"
	"time"

	resources "github.com/isucon/isucon2026/portal/gen/pb/isuxportal/resources"
	admin "github.com/isucon/isucon2026/portal/gen/pb/isuxportal/services/admin"
	audience "github.com/isucon/isucon2026/portal/gen/pb/isuxportal/services/audience"
	contestant "github.com/isucon/isucon2026/portal/gen/pb/isuxportal/services/contestant"
	registration "github.com/isucon/isucon2026/portal/gen/pb/isuxportal/services/registration"
	"github.com/isucon/isucon2026/portal/internal/job"
	"github.com/isucon/isucon2026/portal/tests/testkit"
	"google.golang.org/protobuf/proto"
)

func TestTeamRenameRefreshesCachedDashboards(t *testing.T) {
	for _, scenario := range []string{"admin", "admin-frozen", "registration"} {
		t.Run(scenario, func(t *testing.T) {
			p := testkit.Start(t)
			ctx := context.Background()
			id, leader := p.CreateTeam(t, "original")
			now := time.Now().UTC()
			p.Cfg.Timing.ContestStart = pointer(now.Add(-3 * time.Hour))
			p.Cfg.Timing.ContestFreeze = pointer(now.Add(time.Hour))
			p.Cfg.Timing.ContestEnd = pointer(now.Add(2 * time.Hour))
			if scenario == "admin-frozen" {
				p.Cfg.Timing.ContestFreeze = pointer(now.Add(-time.Hour))
			}
			// Keep the score history fixed throughout the rename, including a score
			// after the freeze that must remain private to staff and the team itself.
			for i, markedAt := range []time.Time{now.Add(-2 * time.Hour), now.Add(-30 * time.Minute)} {
				if _, err := p.DB.Exec(`INSERT INTO benchmark_results(team_id,benchmark_job_id,score,finished,passed,exit_status,marked_at,created_at,updated_at) VALUES($1,$2,$3,true,true,0,$4,$4,$4)`, id, i+1, (i+1)*100, markedAt); err != nil {
					t.Fatal(err)
				}
			}
			if err := p.Jobs.UpdateContestantDashboard(ctx, job.UpdateDashboardArgs{TeamID: id, Frozen: true}); err != nil {
				t.Fatal(err)
			}
			staff := map[string]string{"X-Isux-Session-Staff": "1"}
			member := map[string]string{"X-Isux-Session-Contestant-Id": fmt.Sprint(leader)}
			type dashboard struct {
				path, key string
				headers   map[string]string
				message   func() proto.Message
				item      func(proto.Message) *resources.LeaderboardItem
			}
			dashboards := []dashboard{
				{"/api/admin/dashboard", "leaderboard-v2:admin", staff,
					func() proto.Message { return &admin.DashboardResponse{} },
					func(m proto.Message) *resources.LeaderboardItem {
						return m.(*admin.DashboardResponse).Leaderboard.Teams[0]
					}},
				{fmt.Sprintf("/api/admin/dashboard/teams/%d", id), fmt.Sprintf("dashboard-v2:admin:team-%d", id), staff,
					func() proto.Message { return &admin.SoloDashboardResponse{} },
					func(m proto.Message) *resources.LeaderboardItem {
						return m.(*admin.SoloDashboardResponse).LeaderboardItem
					}},
				{"/api/contestant/dashboard", fmt.Sprintf("dashboard-v2:contestant:team-%d", id), member,
					func() proto.Message { return &contestant.DashboardResponse{} },
					func(m proto.Message) *resources.LeaderboardItem {
						return m.(*contestant.DashboardResponse).LeaderboardItem
					}},
				{"/api/audience/dashboard", "dashboard-v2:audience", nil,
					func() proto.Message { return &audience.DashboardResponse{} },
					func(m proto.Message) *resources.LeaderboardItem {
						return m.(*audience.DashboardResponse).Leaderboard.Teams[0]
					}},
				{fmt.Sprintf("/api/audience/dashboard/teams/%d", id), fmt.Sprintf("dashboard-v2:audience:team-%d", id), nil,
					func() proto.Message { return &audience.SoloDashboardResponse{} },
					func(m proto.Message) *resources.LeaderboardItem {
						return m.(*audience.SoloDashboardResponse).LeaderboardItem
					}},
			}
			previous := make([]*resources.LeaderboardItem, len(dashboards))
			etags := make([]string, len(dashboards))
			for i, d := range dashboards {
				if _, _, ok, err := p.Jobs.Cache.Read(ctx, d.key); err != nil || !ok {
					t.Fatalf("cache %s: exists=%v err=%v", d.key, ok, err)
				}
				res := p.DoPB(t, http.MethodGet, d.path, nil, d.headers)
				if res.StatusCode != http.StatusOK {
					t.Fatalf("initial %s: %d", d.path, res.StatusCode)
				}
				etags[i] = res.Header.Get("ETag")
				msg := d.message()
				testkit.DecodePB(t, res, msg)
				previous[i] = d.item(msg)
				if previous[i].GetTeam().GetName() != "original" {
					t.Fatalf("initial %s: %v", d.path, previous[i])
				}
				wantScore := int64(200)
				if scenario == "admin-frozen" && d.headers == nil {
					wantScore = 100
				}
				if previous[i].GetLatestScore().GetScore() != wantScore {
					t.Fatalf("initial score %s: %v", d.path, previous[i])
				}
			}

			// Use the production DB queue; HTTP success alone must not be mistaken
			// for a refresh. Let a worker consume the job generated by the update.
			queue := &job.DBQueue{DB: p.DB}
			p.Jobs.SetQueue(queue)
			if scenario == "registration" {
				// Registration editing is available only before the contest.
				p.Cfg.Timing.ContestStart = pointer(now.Add(time.Hour))
				res := p.DoPB(t, http.MethodPut, "/api/registration", &registration.UpdateRegistrationRequest{
					Name: "original-leader", TeamName: "renamed", EmailAddress: "original@test.invalid",
				}, member)
				if res.StatusCode != http.StatusOK {
					t.Fatalf("rename: %d %s", res.StatusCode, readAll(t, res))
				}
				res.Body.Close()
				p.Cfg.Timing.ContestStart = pointer(now.Add(-3 * time.Hour))
			} else {
				path := fmt.Sprintf("/api/admin/teams/%d", id)
				msg := &admin.GetTeamResponse{}
				testkit.DecodePB(t, p.DoPB(t, http.MethodGet, path, nil, staff), msg)
				msg.Team.Name = "renamed"
				res := p.DoPB(t, http.MethodPut, path, &admin.UpdateTeamRequest{Team: msg.Team}, staff)
				if res.StatusCode != http.StatusOK {
					t.Fatalf("rename: %d %s", res.StatusCode, readAll(t, res))
				}
				res.Body.Close()
			}
			for {
				worked, err := queue.Work(ctx, p.Jobs)
				if err != nil {
					t.Fatal(err)
				}
				if !worked {
					break
				}
			}
			for i, d := range dashboards {
				headers := map[string]string{}
				for k, v := range d.headers {
					headers[k] = v
				}
				if etags[i] != "" {
					headers["If-None-Match"] = etags[i]
				}
				res := p.DoPB(t, http.MethodGet, d.path, nil, headers)
				if res.StatusCode != http.StatusOK {
					t.Errorf("renamed %s: %d (old ETag must not return 304)", d.path, res.StatusCode)
					res.Body.Close()
					continue
				}
				msg := d.message()
				testkit.DecodePB(t, res, msg)
				got := d.item(msg)
				if got.GetTeam().GetName() != "renamed" {
					t.Errorf("renamed %s: got %q", d.path, got.GetTeam().GetName())
				}
				// Compare the entire item after substituting only the expected name.
				previous[i].Team.Name = "renamed"
				if !proto.Equal(got, previous[i]) {
					t.Errorf("%s: item changed beyond team name\ngot %v\nwant %v", d.path, got, previous[i])
				}
			}
		})
	}
}
