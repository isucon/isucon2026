// Package dump renders the contents of an ISUReal database back into a SQL seed
// file. Every table is written as multi-row INSERT statements (a form of bulk
// insert) so that loading webapp/sql/002-seed.sql stays fast even when the
// fixture grows to many thousands of rows.
package dump

import (
	"context"
	"fmt"
	"io"
	"strings"

	"github.com/jackc/pgx/v5"
)

// batchSize caps how many rows are emitted in a single INSERT statement. Large
// multi-row INSERTs keep the load fast while bounding statement size.
const batchSize = 1000

// tableOrder lists the application tables in foreign-key dependency order.
// Tables that do not exist in the database are skipped. If the database
// contains a table that is missing from this list, Dump fails loudly so newly
// added tables are never silently omitted from the seed.
//
// NOTE: users.profile_image_id -> image_objects.owner_user_id is a circular
// reference. The order below is valid while generated users have no profile
// images; once they do, users must be inserted with a NULL profile_image_id and
// patched afterwards.
var tableOrder = []string{
	"administrators",
	"administrator_sessions",
	"users",
	"image_objects",
	"login_sessions",
	"friend_requests",
	"friendships",
	"follows",
	"block_relations",
	"posting_windows",
	"posts",
	"realmojis",
	"comments",
	"notifications",
}

type column struct {
	name    string
	isBytea bool
}

// Dump writes the entire fixture as a seed SQL file.
func Dump(ctx context.Context, conn *pgx.Conn, w io.Writer) error {
	present, err := listTables(ctx, conn)
	if err != nil {
		return err
	}
	known := make(map[string]bool, len(tableOrder))
	for _, name := range tableOrder {
		known[name] = true
	}
	for name := range present {
		if !known[name] {
			return fmt.Errorf("table %q exists in the database but is missing from dump.tableOrder; add it in dependency order", name)
		}
	}

	fmt.Fprintln(w, "-- 002-seed.sql")
	fmt.Fprintln(w, "-- Generated by webapp/datagen. Do not edit by hand.")
	fmt.Fprintln(w, "-- Regenerate with: (cd webapp/datagen && go run . all)")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "BEGIN;")
	for _, name := range tableOrder {
		if !present[name] {
			continue
		}
		if err := dumpTable(ctx, conn, w, name); err != nil {
			return err
		}
	}
	fmt.Fprintln(w, "COMMIT;")
	return nil
}

func dumpTable(ctx context.Context, conn *pgx.Conn, w io.Writer, name string) error {
	cols, err := tableColumns(ctx, conn, name)
	if err != nil {
		return err
	}
	if len(cols) == 0 {
		return fmt.Errorf("table %q has no columns", name)
	}
	pk, err := primaryKey(ctx, conn, name)
	if err != nil {
		return err
	}
	if len(pk) == 0 {
		pk = []string{cols[0].name}
	}

	selectCols := make([]string, len(cols))
	for i, c := range cols {
		selectCols[i] = quoteIdent(c.name) + "::text"
	}
	orderCols := make([]string, len(pk))
	for i, c := range pk {
		orderCols[i] = quoteIdent(c)
	}
	query := "SELECT " + strings.Join(selectCols, ", ") +
		" FROM " + quoteIdent(name) +
		" ORDER BY " + strings.Join(orderCols, ", ")

	rows, err := conn.Query(ctx, query)
	if err != nil {
		return fmt.Errorf("select %s: %w", name, err)
	}
	defer rows.Close()

	insertHeader := "INSERT INTO " + quoteIdent(name) + " (" + strings.Join(quoteIdents(columnsNames(cols)), ", ") + ") VALUES"
	commented := false
	var batch [][]string

	flush := func() error {
		if len(batch) == 0 {
			return nil
		}
		if !commented {
			if _, err := fmt.Fprintf(w, "\n-- %s\n", name); err != nil {
				return err
			}
			commented = true
		}
		if _, err := fmt.Fprintln(w, insertHeader); err != nil {
			return err
		}
		for i, tuple := range batch {
			terminator := ","
			if i == len(batch)-1 {
				terminator = ";"
			}
			if _, err := fmt.Fprintf(w, "  (%s)%s\n", strings.Join(tuple, ", "), terminator); err != nil {
				return err
			}
		}
		batch = batch[:0]
		return nil
	}

	for rows.Next() {
		values, err := rows.Values()
		if err != nil {
			return fmt.Errorf("read %s: %w", name, err)
		}
		tuple := make([]string, len(cols))
		for i := range cols {
			tuple[i] = literal(cols[i], values[i])
		}
		batch = append(batch, tuple)
		if len(batch) >= batchSize {
			if err := flush(); err != nil {
				return err
			}
		}
	}
	if err := rows.Err(); err != nil {
		return fmt.Errorf("iterate %s: %w", name, err)
	}
	return flush()
}

func columnsNames(cols []column) []string {
	names := make([]string, len(cols))
	for i, c := range cols {
		names[i] = c.name
	}
	return names
}

// literal renders a single value, received as text, as a SQL literal. String
// constants are written as E'...' literals so the result is correct regardless
// of the session's standard_conforming_strings setting, and bytea is emitted
// with decode() to avoid any backslash-escape ambiguity.
func literal(c column, value any) string {
	if value == nil {
		return "NULL"
	}
	text, ok := value.(string)
	if !ok {
		text = fmt.Sprint(value)
	}
	if c.isBytea {
		return "decode('" + strings.TrimPrefix(text, `\x`) + "', 'hex')"
	}
	return quoteText(text)
}

func quoteText(s string) string {
	var b strings.Builder
	b.Grow(len(s) + 3)
	b.WriteString("E'")
	for i := 0; i < len(s); i++ {
		switch ch := s[i]; ch {
		case '\'':
			b.WriteString(`\'`)
		case '\\':
			b.WriteString(`\\`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		default:
			if ch < 0x20 {
				fmt.Fprintf(&b, `\%03o`, ch)
			} else {
				b.WriteByte(ch)
			}
		}
	}
	b.WriteString("'")
	return b.String()
}

func quoteIdent(s string) string {
	return `"` + strings.ReplaceAll(s, `"`, `""`) + `"`
}

func quoteIdents(names []string) []string {
	quoted := make([]string, len(names))
	for i, name := range names {
		quoted[i] = quoteIdent(name)
	}
	return quoted
}

func listTables(ctx context.Context, conn *pgx.Conn) (map[string]bool, error) {
	rows, err := conn.Query(ctx, `
		SELECT table_name
		FROM information_schema.tables
		WHERE table_schema = 'public' AND table_type = 'BASE TABLE'
	`)
	if err != nil {
		return nil, fmt.Errorf("list tables: %w", err)
	}
	defer rows.Close()
	tables := map[string]bool{}
	for rows.Next() {
		var name string
		if err := rows.Scan(&name); err != nil {
			return nil, err
		}
		tables[name] = true
	}
	return tables, rows.Err()
}

func tableColumns(ctx context.Context, conn *pgx.Conn, table string) ([]column, error) {
	rows, err := conn.Query(ctx, `
		SELECT column_name, udt_name
		FROM information_schema.columns
		WHERE table_schema = 'public' AND table_name = $1
		ORDER BY ordinal_position
	`, table)
	if err != nil {
		return nil, fmt.Errorf("columns of %s: %w", table, err)
	}
	defer rows.Close()
	var cols []column
	for rows.Next() {
		var c column
		var udt string
		if err := rows.Scan(&c.name, &udt); err != nil {
			return nil, err
		}
		c.isBytea = udt == "bytea"
		cols = append(cols, c)
	}
	return cols, rows.Err()
}

func primaryKey(ctx context.Context, conn *pgx.Conn, table string) ([]string, error) {
	rows, err := conn.Query(ctx, `
		SELECT a.attname
		FROM pg_index i
		JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = ANY(i.indkey)
		WHERE i.indrelid = $1::regclass AND i.indisprimary
		ORDER BY a.attnum
	`, "public."+quoteIdent(table))
	if err != nil {
		return nil, fmt.Errorf("primary key of %s: %w", table, err)
	}
	defer rows.Close()
	var cols []string
	for rows.Next() {
		var name string
		if err := rows.Scan(&name); err != nil {
			return nil, err
		}
		cols = append(cols, name)
	}
	return cols, rows.Err()
}
