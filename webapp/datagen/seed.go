// date は COPY で date 型として書く値。
type date time.Time

// copyWriter は psql がそのまま流せる COPY ... FROM stdin 形式で行を書く。
type copyWriter struct {
	w   *bufio.Writer
	err error
}

func (c *copyWriter) printf(format string, args ...any) {
	if c.err == nil {
		_, c.err = fmt.Fprintf(c.w, format, args...)
	}
}

func (c *copyWriter) copy(table string, columns []string, rows func(row func(values ...any))) {
	c.printf("COPY %s (%s) FROM stdin;\n", table, strings.Join(columns, ", "))
	rows(func(values ...any) {
		if len(values) != len(columns) {
			panic(fmt.Sprintf("%s: %d values for %d columns", table, len(values), len(columns)))
		}
		fields := make([]string, len(values))
		for i, value := range values {
			fields[i] = copyValue(value)
		}
		c.printf("%s\n", strings.Join(fields, "\t"))
	})
	c.printf("\\.\n\n")
}

// copyValue は COPY のテキスト形式で 1 つの値を表す。NULL は \N、バックスラッシュと
// 制御文字はエスケープし、bytea は \x の 16 進表記（バックスラッシュは二重にする）にする。
func copyValue(value any) string {
	switch v := value.(type) {
	case nil:
		return `\N`
	case string:
		return escapeCopyText(v)
	case *string:
		if v == nil {
			return `\N`
		}
		return escapeCopyText(*v)
	case float64:
		return strconv.FormatFloat(v, 'f', -1, 64)
	case *float64:
		if v == nil {
			return `\N`
		}
		return strconv.FormatFloat(*v, 'f', -1, 64)
	case time.Time:
		return v.UTC().Format("2006-01-02 15:04:05.999999Z07:00")
	case *time.Time:
		if v == nil {
			return `\N`
		}
		return v.UTC().Format("2006-01-02 15:04:05.999999Z07:00")
	case date:
		return time.Time(v).Format(time.DateOnly)
	case []byte:
		return `\\x` + hex.EncodeToString(v)
	default:
		panic(fmt.Sprintf("unsupported COPY value %T", value))
	}
}

var copyTextEscaper = strings.NewReplacer(`\`, `\\`, "\t", `\t`, "\n", `\n`, "\r", `\r`)

func escapeCopyText(value string) string {
	return copyTextEscaper.Replace(value)
}

// seedStats は書き出した行の数。
type seedStats struct {
	users, posts, realMojis, comments, images int
	imageBytes                                int64
}

// writeSeed は world 全体を 1 つのトランザクションで投入する SQL を書く。投稿とそれに
// 付くものは日ごとに作っては書くので、履歴全体をメモリに持たない。表ごとに履歴を
// 作り直すが、画像を除けば生成は軽い。
func writeSeed(out io.Writer, world *dataset.World) (seedStats, error) {
	var stats seedStats
	c := &copyWriter{w: bufio.NewWriter(out)}
	c.printf("-- 002-seed.sql\n-- Generated by webapp/datagen. Do not edit by hand.\n-- Regenerate with: make datagen\n\nBEGIN;\n\n")
	days := func(each func(posts []*dataset.Post)) {
		for day := range world.Config.Days {
			each(world.PostsOn(day))
		}
	}

	c.copy("administrators", []string{"id", "username", "password_hash", "created_at"}, func(row func(...any)) {
		row(dataset.AdministratorID, dataset.AdministratorUsername, dataset.HashCredential(dataset.AdministratorPassword), world.Config.EndDate)
	})
	// users.profile_image_id と image_objects.owner_user_id は互いを参照するので、ユーザーを
	// プロフィール画像なしで入れ、画像を入れたあとで紐づける。
	c.copy("users", []string{"id", "username", "secret_key_hash", "display_name", "bio", "region", "account_type", "status", "deleted_at", "created_at", "updated_at"}, func(row func(...any)) {
		for _, u := range world.Users {
			updatedAt := u.CreatedAt
			if u.DeletedAt != nil {
				updatedAt = *u.DeletedAt
			}
			row(u.ID, u.Username, dataset.HashCredential(u.SecretKey), u.DisplayName, u.Bio, u.Region, u.AccountType, u.Status, u.DeletedAt, u.CreatedAt, updatedAt)
			stats.users++
		}
	})
	c.copy("image_objects", []string{"id", "owner_user_id", "data", "media_type", "created_at"}, func(row func(...any)) {
		write := func(images []*dataset.Image) {
			for i, data := range renderImages(world, images) {
				row(images[i].ID, images[i].OwnerID, data, "image/jpeg", images[i].CreatedAt)
				stats.images++
				stats.imageBytes += int64(len(data))
			}
		}
		var profiles []*dataset.Image
		for _, u := range world.Users {
			if u.ProfileImage != nil {
				profiles = append(profiles, u.ProfileImage)
			}
		}
		write(profiles)
		days(func(posts []*dataset.Post) {
			var images []*dataset.Image
			for _, p := range posts {
				images = append(images, p.Image)
				for _, r := range p.RealMojis {
					images = append(images, r.Image)
				}
			}
			write(images)
		})
	})
	c.printf("CREATE TEMPORARY TABLE seed_profile_images (user_id varchar(36) PRIMARY KEY, image_id varchar(36) NOT NULL) ON COMMIT DROP;\n")
	c.copy("seed_profile_images", []string{"user_id", "image_id"}, func(row func(...any)) {
		for _, u := range world.Users {
			if u.ProfileImage != nil {
				row(u.ID, u.ProfileImage.ID)
			}
		}
	})
	c.printf("UPDATE users SET profile_image_id = s.image_id FROM seed_profile_images s WHERE users.id = s.user_id;\n\n")

	c.copy("friend_requests", []string{"id", "requester_id", "recipient_id", "status", "created_at", "updated_at"}, func(row func(...any)) {
		for _, r := range world.FriendRequests {
			row(r.ID, r.RequesterID, r.RecipientID, r.Status, r.CreatedAt, r.UpdatedAt)
		}
	})
	c.copy("friendships", []string{"id", "user_low_id", "user_high_id", "source_request_id", "created_at", "updated_at"}, func(row func(...any)) {
		for _, f := range world.Friendships {
			row(f.ID, f.UserLowID, f.UserHighID, f.SourceRequestID, f.CreatedAt, f.CreatedAt)
		}
	})
	c.copy("follows", []string{"id", "follower_id", "followee_id", "created_at", "updated_at"}, func(row func(...any)) {
		for _, f := range world.Follows {
			row(f.ID, f.FollowerID, f.FolloweeID, f.CreatedAt, f.CreatedAt)
		}
	})
	c.copy("block_relations", []string{"id", "blocker_id", "blocked_id", "created_at"}, func(row func(...any)) {
		for _, b := range world.Blocks {
			row(b.ID, b.BlockerID, b.BlockedID, b.CreatedAt)
		}
	})
	c.copy("posting_windows", []string{"id", "region", "local_date", "starts_at", "on_time_deadline", "ended_at", "created_at"}, func(row func(...any)) {
		for _, w := range world.Windows {
			row(w.ID, w.Region, date(w.LocalDate), w.StartsAt, w.OnTimeDeadline, w.EndedAt, w.StartsAt)
		}
	})
	c.copy("posts", []string{"id", "author_id", "posting_window_id", "image_id", "caption", "visibility", "location_kind", "latitude", "longitude", "locality", "posted_at", "created_at", "deleted_at"}, func(row func(...any)) {
		days(func(posts []*dataset.Post) {
			for _, p := range posts {
				row(p.ID, p.AuthorID, p.WindowID, p.Image.ID, p.Caption, p.Visibility, p.Location.Kind, p.Location.Latitude, p.Location.Longitude, p.Location.Locality, p.PostedAt, p.PostedAt, p.DeletedAt)
				stats.posts++
			}
		})
	})
	c.copy("realmojis", []string{"id", "post_id", "reactor_id", "image_id", "reaction_type", "created_at", "replaced_at", "deleted_at"}, func(row func(...any)) {
		days(func(posts []*dataset.Post) {
			for _, p := range posts {
				for _, r := range p.RealMojis {
					row(r.ID, r.PostID, r.ReactorID, r.Image.ID, r.ReactionType, r.CreatedAt, r.ReplacedAt, nil)
					stats.realMojis++
				}
			}
		})
	})
	c.copy("comments", []string{"id", "post_id", "author_id", "body", "created_at", "deleted_at"}, func(row func(...any)) {
		days(func(posts []*dataset.Post) {
			for _, p := range posts {
				for _, cm := range p.Comments {
					row(cm.ID, cm.PostID, cm.AuthorID, cm.Body, cm.CreatedAt, cm.DeletedAt)
					stats.comments++
				}
			}
		})
	})
	c.copy("notifications", []string{"id", "user_id", "posting_window_id", "created_at"}, func(row func(...any)) {
		for day := range world.Config.Days {
			for _, n := range world.NotificationsOn(day) {
				row(n.ID, n.UserID, n.WindowID, n.CreatedAt)
			}
		}
	})

	c.printf("COMMIT;\n")
	if c.err != nil {
		return stats, c.err
	}
	return stats, c.w.Flush()
}

// renderImages は画像の中身を並行に作り、images の順で返す。画像の生成が datagen の
// 時間の大半を占める。
func renderImages(world *dataset.World, images []*dataset.Image) [][]byte {
	data := make([][]byte, len(images))
	next := make(chan int)
	var wg sync.WaitGroup
	for range runtime.NumCPU() {
		wg.Go(func() {
			for i := range next {
				data[i] = world.ImageBytes(images[i])
			}
		})
	}
	for i := range images {
		next <- i
	}
	close(next)
	wg.Wait()
	return data
}
